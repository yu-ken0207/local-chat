import { plainText } from '../src/lib/plainText';

test('朗讀用純文字：去掉 Markdown 符號、程式碼區塊不念、連結只念文字', () => {
  const md = [
    '## 結論',
    '',
    '這是 **重點** 和 `變數`，參考 [官方文件](https://x.y)。',
    '',
    '- 第一項',
    '- [x] 完成的事',
    '',
    '> 引用',
    '',
    '```python',
    'print(1)',
    '```',
    '',
    '| 欄 | 值 |',
    '|---|---:|',
    '| a | 1 |',
  ].join('\n');
  expect(plainText(md)).toBe(['結論', '', '這是 重點 和 變數，參考 官方文件。', '', '第一項', '完成的事', '', '引用', '', '（程式碼）', '', ' 欄 值 ', '', ' a 1'].join('\n'));
});

test('串流中沒結束的程式碼區塊也不念', () => {
  expect(plainText('看這段\n```js\nconst a = 1')).toBe('看這段\n（程式碼）');
});
